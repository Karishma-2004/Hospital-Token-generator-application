import { jsPDF } from 'jspdf';

/** Builds and downloads the prescription as a PDF file. `data` is the API response of
 *  GET /appointments/<id>/prescription/ */
export function downloadPrescriptionPdf(data) {
  const { prescription: rx, appointment, doctor, hospital } = data;
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  const left = 15;
  const width = 180;
  let y = 18;

  const ensure = (needed) => {
    if (y + needed > 280) {
      doc.addPage();
      y = 18;
    }
  };
  const write = (text, { size = 11, bold = false, gap = 2, indent = 0, color = 20 } = {}) => {
    doc.setFont('helvetica', bold ? 'bold' : 'normal');
    doc.setFontSize(size);
    doc.setTextColor(color);
    const lines = doc.splitTextToSize(String(text), width - indent);
    lines.forEach((line) => {
      ensure(size * 0.5);
      doc.text(line, left + indent, y);
      y += size * 0.45;
    });
    y += gap;
  };
  const rule = () => {
    ensure(4);
    doc.setDrawColor(200);
    doc.line(left, y, left + width, y);
    y += 5;
  };

  write(hospital.name, { size: 18, bold: true, gap: 1, color: 22 });
  write([hospital.address, hospital.city].filter(Boolean).join(', '), { size: 10, gap: 0, color: 90 });
  write(`Phone: ${hospital.phone}`, { size: 10, gap: 3, color: 90 });
  rule();

  write(doctor.name, { size: 13, bold: true, gap: 0 });
  write(`${doctor.specialization} · ${doctor.department}`, { size: 10, gap: 0, color: 90 });
  write(`Registration no: ${doctor.registration_number}`, { size: 10, gap: 4, color: 90 });

  write(`Patient: ${appointment.patient_name}`, { bold: true, gap: 0 });
  write(`Date: ${appointment.appointment_date}    Token: #${appointment.token_number}`, { size: 10, gap: 4, color: 90 });
  rule();

  write('Diagnosis', { size: 10, bold: true, gap: 0, color: 90 });
  write(rx.diagnosis, { gap: 4 });
  if (rx.notes) {
    write('Clinical notes', { size: 10, bold: true, gap: 0, color: 90 });
    write(rx.notes, { gap: 4 });
  }

  write('Rx', { size: 16, bold: true, gap: 2 });
  if (!rx.items.length) write('No medicines prescribed.', { size: 10, gap: 4, color: 90 });
  rx.items.forEach((item, index) => {
    const detail = [item.dosage, item.frequency, item.duration].filter(Boolean).join('  ·  ');
    write(`${index + 1}. ${item.medicine}`, { bold: true, gap: 0 });
    if (detail) write(detail, { size: 10, indent: 6, gap: 0 });
    if (item.instructions) write(item.instructions, { size: 10, indent: 6, gap: 0, color: 90 });
    y += 2;
  });

  if (rx.advice) {
    y += 2;
    write('Advice', { size: 10, bold: true, gap: 0, color: 90 });
    write(rx.advice, { gap: 4 });
  }
  if (rx.follow_up_date) write(`Follow-up on: ${rx.follow_up_date}`, { bold: true, gap: 4 });

  ensure(14);
  y += 6;
  doc.setFontSize(9);
  doc.setTextColor(130);
  doc.text('Generated by Qenova. This prescription is valid only with the doctor\'s registration details above.', left, y);

  doc.save(`prescription-token-${appointment.token_number}-${appointment.appointment_date}.pdf`);
}
